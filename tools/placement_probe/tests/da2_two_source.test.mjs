// da2_two_source.test.mjs — DA2-COV/P3 permanent regression: TWO CONTRIBUTING
// SOURCES in the retained-candidate aggregation (RUN_ID
// PE_935_PLACEMENT_PA2_RECEIPT_QUALIFICATION_CORRECTION_R1_20261011, contract §7).
//
// The external Desktop post-audit measured a cap32 case with contributions 29 + 3
// records from two actually-participating inputs; the committed B5 control only had
// cap4 (second input never opened). This regression reproduces the externally
// measured case THROUGH THE ACTUAL SCAN of the UNCHANGED scanner: one records80()
// payload naturally emits exactly 29 candidates, so at cap 32 the first input
// contributes 29 rows and the shared global retained-candidates budget caps the
// second input's found-collection at 3 — 29 + 3 = 32 total, both files opened.
// The values are generated by the scan, never fabricated; if 29+3 cannot be
// reproduced within the unchanged scanner, the test FAILS (no limit changes, no
// arithmetic substitution).
//
// The identity observer is the WeakMap scalar-identity observer from
// tools/placement_probe/qualification/pa2_r1/two_source.mjs (marker-injection
// pattern attributed to da2_retained.test.mjs BASE): it stores ONLY scalar ids and
// counters — no candidate objects are retained as audit roots. An alias counts
// once; an actual copied object counts separately. cap4/cap256 and the forced-copy
// detection control remain in da2_retained.test.mjs (unchanged; cap4 still does not
// prove two contributing sources — that is exactly the gap this test closes).
import test from 'node:test';
import assert from 'node:assert/strict';
import os from 'node:os';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { measureTwoSource, TWO_SOURCE_TARGETS } from '../qualification/pa2_r1/two_source.mjs';
import { records80 } from './fixtures.mjs';

const TESTS = path.dirname(fileURLToPath(import.meta.url));
const TOOL = path.join(TESTS, '..', 'placement_probe.mjs');
const ROOT = path.resolve(TESTS, '..', '..', '..');
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'pe-t-da2cov-'));

test('DA2-COV: cap32 two contributing sources through the actual scan — 29 + 3 = 32, per-phase peaks <= 32, both inputs opened', () => {
  const root = tmp(); try {
    const ts = measureTwoSource({ toolPath: TOOL, worktreeRoot: ROOT, dir: path.join(root, 'cap32') });
    const [c1, c2] = ts.perSource.contributions;
    // exact externally measured case, generated by the scan
    assert.ok(c1 && c2, 'two input contributions recorded');
    assert.equal(c1.rows, TWO_SOURCE_TARGETS.SOURCE_1_CONTRIBUTION, 'source 1 must contribute exactly 29 rows through the scan (got ' + c1?.rows + ')');
    assert.equal(c2.rows, TWO_SOURCE_TARGETS.SOURCE_2_CONTRIBUTION, 'source 2 must contribute exactly 3 rows through the scan (got ' + c2?.rows + ')');
    assert.equal(ts.totals.candidateCount, TWO_SOURCE_TARGETS.TOTAL_CANDIDATE_ROWS);
    assert.equal(ts.totals.trackedPeak, TWO_SOURCE_TARGETS.RETAINED_CAP);
    // both input files opened and contributing, proven by per-source provenance
    assert.equal(ts.totals.bothInputsOpened, true, 'both declared inputs must be opened (sources.json parseStatus)');
    assert.equal(ts.totals.twoSourcesContributing, true);
    assert.deepEqual(ts.perSource.sourcesParseStatus.map(s => s.parseStatus), ['OK', 'OK']);
    assert.equal(ts.totals.forwardContributionsPerInput[c1.path], 29, 'the observer records 29 forwards for source 1');
    assert.equal(ts.totals.forwardContributionsPerInput[c2.path], 3, 'the observer records 3 forwards for source 2');
    // bounded identity observer: per-phase distinct live records within the cap
    assert.ok(ts.peaks.creation <= TWO_SOURCE_TARGETS.PEAK_DISTINCT_CREATION_MAX, 'creation peak ' + ts.peaks.creation);
    assert.ok(ts.peaks.forward <= TWO_SOURCE_TARGETS.PEAK_DISTINCT_FORWARD_MAX, 'forward peak ' + ts.peaks.forward);
    assert.ok(ts.peaks.serialization <= TWO_SOURCE_TARGETS.PEAK_DISTINCT_SERIALIZATION_MAX, 'serialization peak ' + ts.peaks.serialization);
    assert.equal(ts.totals.serialization.allSerializedAreLiveRows, true, 'serialized identities ARE the live rows (alias, not copy)');
    assert.equal(ts.peaks.serialization, 32, 'serialization walks all 32 live rows exactly once');
    // observer discipline: only scalar identities recorded, no candidate objects retained as audit roots
    for (const p of ts.phases) assert.equal(p.auditObjectsRetained, 0);
    // instrumented == ordinary execution: four outputs byte-for-byte + identical budgets
    for (const f of Object.keys(ts.byteIdentical)) assert.ok(ts.byteIdentical[f], 'byte-identical output: ' + f);
    assert.equal(ts.budgetsIdentical, true);
    assert.equal(ts.un.exitCode, 0, ts.un.stderr);
    assert.equal(ts.totals.coverage, 'PARTIAL');
    assert.ok(ts.totals.exhausted.includes('RETAINED_CANDIDATES'), 'the cap stop is visible in the budgets');
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});

test('DA2-COV: negative protection — a zero/missing second contribution is DETECTED and refused (cap29 control: the second input is never opened)', () => {
  const root = tmp(); try {
    // cap 29: the first records80() input fills the cap exactly; the second input is
    // never opened — the same shape as the historical cap4 gap. The regression's
    // required predicates (second contribution === 3, both inputs opened) would be
    // VIOLATED here: the measurement must expose the missing second contribution
    // rather than silently passing.
    const dir = path.join(root, 'cap29'); fs.mkdirSync(dir, { recursive: true });
    const ids = path.join(dir, 'ids.json');
    fs.writeFileSync(ids, JSON.stringify({ S_tpl: [4057, 4058], S_model: [218757] }));
    const raws = [];
    for (let i = 0; i < 2; i++) { const f = path.join(dir, `raw_${i}.vfs`); fs.writeFileSync(f, records80()); raws.push(f); }
    const out = path.join(dir, 'out'); fs.mkdirSync(out, { recursive: true });
    const res = spawnSync(process.execPath, [TOOL, '--repo', ROOT, '--ids', ids, '--out', out, ...raws.flatMap(n => ['--input', n]), '--budget-retained-candidates', '29'], { encoding: 'utf8', timeout: 180000 });
    assert.equal(res.status, 0, res.stderr);
    const sources = JSON.parse(fs.readFileSync(path.join(out, 'sources.json'), 'utf8'));
    assert.equal(sources[0].parseStatus, 'OK');
    assert.equal(sources[1].parseStatus, 'NOT_OPENED_BUDGET', 'at cap29 the second input is never opened — the exact historical gap shape');
    const csv = fs.readFileSync(path.join(out, 'placement_candidates.csv'), 'utf8').trim().split('\n').slice(1);
    const perSource = {};
    for (const line of csv) { const input = line.split(',')[0]; perSource[input] = (perSource[input] || 0) + 1; }
    const contributions = raws.map(r => perSource[r] ?? 0);
    assert.deepEqual(contributions, [29, 0], 'the missing second contribution is measurable, not hidden');
    // the regression's own required predicate refuses this shape
    const twoSourcesContributing = contributions.length === 2 && contributions.every(c => c > 0);
    assert.equal(twoSourcesContributing, false, 'a cap29-style run must NOT satisfy the two-contributing-sources predicate');
    assert.equal(contributions[1] === TWO_SOURCE_TARGETS.SOURCE_2_CONTRIBUTION && twoSourcesContributing, false);
  } finally { fs.rmSync(root, { recursive: true, force: true }); }
});
